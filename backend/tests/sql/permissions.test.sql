begin;
create extension if not exists pgtap with schema extensions;
set search_path = public, extensions;
select plan(23);
select ok((select relrowsecurity from pg_class where oid='public.tasks'::regclass), 'tasks RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.construction_sites'::regclass), 'sites RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.task_status_events'::regclass), 'history RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.profiles'::regclass), 'profiles RLS enabled');
select ok(not has_table_privilege('anon','public.tasks','SELECT'), 'anonymous cannot select tasks');
select ok(not has_table_privilege('authenticated','public.tasks','UPDATE'), 'direct task updates denied');
select ok(not has_table_privilege('authenticated','public.tasks','INSERT'), 'direct task inserts denied');
select ok(not has_table_privilege('authenticated','public.profiles','UPDATE'), 'self-promotion denied');
select ok(not has_table_privilege('authenticated','public.task_status_events','INSERT'), 'history cannot be forged');
select ok(not has_table_privilege('authenticated','public.task_status_events','UPDATE'), 'history cannot be edited');
select ok(not has_table_privilege('authenticated','public.task_status_events','DELETE'), 'history cannot be deleted');
select ok(not has_table_privilege('crm_backend','public.task_status_events','UPDATE'), 'backend cannot edit history');
select ok(not has_function_privilege('anon','public.transition_task(uuid,integer,public.task_status,text)','EXECUTE'), 'anonymous RPC forbidden');
select ok(has_function_privilege('authenticated','public.transition_task(uuid,integer,public.task_status,text)','EXECUTE'), 'authenticated can call transition command');
select ok(not (select rolcanlogin or rolbypassrls from pg_roles where rolname='crm_backend'), 'backend role cannot log in or bypass RLS');
select ok(not has_table_privilege('authenticated','private.creation_requests','SELECT'), 'creation keys are private');
select ok(not has_table_privilege('authenticated','private.client_errors','SELECT'), 'diagnostics are private');
select ok(not has_table_privilege('authenticated','private.client_errors','INSERT'), 'diagnostics require command validation');
select ok(not has_function_privilege('anon','public.create_site(text,text,uuid)','EXECUTE'), 'anonymous creation forbidden');
select ok(has_function_privilege('authenticated','public.create_site(text,text,uuid)','EXECUTE'), 'authenticated creation available');
select ok(not has_function_privilege('authenticated','private.creation_request(uuid,text,jsonb)','EXECUTE'), 'creation helper is private');
select ok(not has_function_privilege('anon','public.report_client_error(uuid,text,text,text,text)','EXECUTE'), 'anonymous diagnostics forbidden');
select ok(not has_schema_privilege('crm_backend','public','CREATE'), 'temporary owner-transfer privilege revoked');
select * from finish();
rollback;
